const assert = require('node:assert/strict');
const ui = require('../../client-ui.js');
assert.equal(ui.safeUrl('javascript:alert(1)'), '');
assert.equal(ui.safeUrl('https://user:password@example.com'), '');
assert.equal(ui.safeUrl('https://example.gov.cn/a'), 'https://example.gov.cn/a');
const answer = ui.markdown('# 标题\n\n**重点**\n- 第一项\n- 第二项\n\n| 数据 | 结果 |\n|---|---|\n| A | 1 |\n\n<script>alert(1)</script>');
assert.ok(answer.includes('<h3>标题</h3>'));
assert.ok(answer.includes('<strong>重点</strong>'));
assert.ok(answer.includes('<table>'));
assert.ok(!answer.includes('<script>'));
assert.ok(answer.includes('&lt;script&gt;'));
const citations = ui.citations([{document_id:'D1',title:'文件',chunk_index:0,source_url:'https://example.gov.cn/a'},{document_id:'D1',title:'文件',chunk_index:1,source_url:'https://example.gov.cn/a'}]);
assert.equal((citations.match(/class="source-card"/g)||[]).length, 1);
assert.ok(citations.includes('2 个检索片段'));
assert.ok(!ui.citations([{document_id:'D',source_url:'javascript:alert(1)'}]).includes('href='));
console.log('Client UI: 11 assertions passed (escaped markup, tables, safe links, source deduplication).');
const revised = ui.currentAssumptions({annualElectricity:100000,electricityPrice:.538,carbonFactor:.5},[{name:'照明假设',investment:48000,subsidy:0,annualOm:300,annualElectricitySaving:12000}]).join(' ');
assert.ok(revised.includes('48000'));
assert.ok(!revised.includes('60000'));
assert.ok(revised.includes('假设'));
console.log('Current assumption export: 3 assertions passed.');
